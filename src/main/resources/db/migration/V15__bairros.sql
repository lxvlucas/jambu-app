-- Mesma normalização de NomesRestaurantes.normalizar: sem acento, minúsculas, só letras e números.
CREATE FUNCTION jambu_normalizar(texto text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
    SELECT trim(regexp_replace(translate(lower(texto), 'áàâãäéèêëíìîïóòôõöúùûüç', 'aaaaaeeeeiiiiooooouuuuc'),
                               '[^a-z0-9]+', ' ', 'g'))
$$;
-- Ponto de bairro mais próximo, até 2 km (distância plana corrigida pela latitude, suficiente na ilha).
CREATE FUNCTION jambu_bairro_do_ponto(lat double precision, lon double precision) RETURNS varchar LANGUAGE sql STABLE AS $$
    SELECT b.nome FROM bairros b,
        LATERAL (SELECT 111320 * sqrt(power(b.latitude - lat, 2)
                                      + power((b.longitude - lon) * cos(radians(lat)), 2)) AS metros) d
    WHERE d.metros <= 2000
    ORDER BY d.metros, b.osm_id LIMIT 1
$$;

-- Endereço do Overture que cita um bairro conhecido vale mais que o ponto mais próximo, desde que esse
-- bairro tenha um ponto a até 3 km do pin (evita "Rua do Turu" longe do Turu). Nome mais longo primeiro
-- ("Jardim Renascença" antes de "Renascença"). Sem isso, o ponto mais próximo, até 2 km.
-- O nome da rua não conta: se o endereço começa com um tipo de via ("Rua Tobias Barreto, Madre Deus"),
-- o trecho até a primeira vírgula é ignorado, porque o bairro vem depois dele.
CREATE FUNCTION jambu_sem_logradouro(endereco text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE
        WHEN endereco IS NULL THEN NULL
        WHEN jambu_normalizar(split_part(endereco, ',', 1))
             ~ '^(rua|r|avenida|av|estrada|estr|travessa|tv|trav|alameda|al|rodovia|rod|praca|pca|largo|beco|via|viela)( |$)'
            THEN CASE WHEN position(',' in endereco) = 0 THEN NULL ELSE substr(endereco, position(',' in endereco) + 1) END
        ELSE endereco
    END
$$;
CREATE FUNCTION jambu_bairro(lat double precision, lon double precision, endereco text) RETURNS varchar LANGUAGE sql STABLE AS $$
    SELECT coalesce(
        (SELECT b.nome FROM bairros b,
             LATERAL (SELECT 111320 * sqrt(power(b.latitude - lat, 2)
                                           + power((b.longitude - lon) * cos(radians(lat)), 2)) AS metros) d
         WHERE jambu_sem_logradouro(endereco) IS NOT NULL AND d.metros <= 3000
           AND ' ' || jambu_normalizar(jambu_sem_logradouro(endereco)) || ' ' LIKE '% ' || b.nome_normalizado || ' %'
         ORDER BY length(b.nome_normalizado) DESC, d.metros, b.osm_id LIMIT 1),
        jambu_bairro_do_ponto(lat, lon))
$$;

ALTER TABLE restaurantes ADD COLUMN bairro varchar(100);
ALTER TABLE restaurantes ADD COLUMN bairro_normalizado varchar(100);
-- O banco preenche o bairro sempre que o restaurante nasce ou muda de pin ou de endereço: vale para cadastro,
-- importação do Overture, casamento (T05) e revisão dos founders, sem repetir a regra no código.
CREATE FUNCTION jambu_preencher_bairro() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.latitude IS NULL OR NEW.longitude IS NULL THEN
        NEW.bairro := NULL;
    ELSE
        NEW.bairro := jambu_bairro(NEW.latitude, NEW.longitude, NEW.endereco);
    END IF;
    NEW.bairro_normalizado := CASE WHEN NEW.bairro IS NULL THEN NULL ELSE jambu_normalizar(NEW.bairro) END;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_restaurantes_bairro BEFORE INSERT OR UPDATE OF latitude, longitude, endereco ON restaurantes
    FOR EACH ROW EXECUTE FUNCTION jambu_preencher_bairro();
UPDATE restaurantes SET bairro = jambu_bairro(latitude, longitude, endereco) WHERE latitude IS NOT NULL;
UPDATE restaurantes SET bairro_normalizado = jambu_normalizar(bairro) WHERE bairro IS NOT NULL;
-- Busca por "nome + bairro" ("coisas do cohajap"), com trigramas.
CREATE INDEX idx_restaurantes_nome_bairro_trgm ON restaurantes
    USING gin ((nome_normalizado || ' ' || coalesce(bairro_normalizado, '')) gin_trgm_ops) WHERE situacao <> 'REJEITADO';
